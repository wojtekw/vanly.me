const companyById = Object.fromEntries(companies.map((c) => [c.id, c]));
const vehicles = raw.map(
  ([companyId, id, name, type, mid, high, low, seats, sleeps, auto, pets, km, deposit, source]) => {
    const c = companyById[companyId],
      defaults = typeDefaults[type];
    return {
      id,
      company_id: companyId,
      name,
      type,
      asset: defaults.asset,
      city: c.city,
      lat: c.lat,
      lng: c.lng,
      seats,
      sleeps,
      daily: mid * 100,
      prep: c.settings.prep,
      deposit: deposit * 100,
      min_days: c.settings.minDays,
      auto,
      pets,
      instant: id.length % 2 === 0,
      km,
      features: defaults.features,
      description: `${name} w fikcyjnej flocie ${c.name}. Oferta demonstracyjna odwzorowuje typ pojazdu, poziom ceny i warunki spotykane w aktualnych polskich cennikach, ale nie jest ofertą firmy źródłowej.`,
      tagline:
        type === 'campervan'
          ? 'Zwinny na trasie, wygodny na postoju.'
          : type === 'offroad'
            ? 'Dalej od miasta, bliżej własnego rytmu.'
            : type === 'alcove'
              ? 'Więcej miejsc dla wspólnej podróży.'
              : 'Wygodna przestrzeń na dłuższą drogę.',
      pricing: { low: low * 100, medium: mid * 100, high: high * 100 },
      source,
    };
  },
);

